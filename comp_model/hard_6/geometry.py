"""
Геометрия двумерного среза сердца (4-камерная проекция).

Сердце строится в собственной системе координат (X, Y):
начало - центр атриовентрикулярного кольца, ось Y направлена
к верхушке, ось X - к левой стороне пациента. Затем срез поворачивается
на угол ANGLE, чтобы анатомическая ось сердца была наклонена влево-вниз,
как в грудной клетке (нормальная электрическая ось около +60 градусов).

На изображении левая сторона пациента - справа (как на рентгенограмме).
"""

import numpy as np

# Типы тканей
NONE, ATRIA, AVN, HIS, PURK, VENT, SCAR, BORDER = range(8)
NAMES = {
    NONE: "нет ткани", ATRIA: "предсердия", AVN: "АВ-узел",
    HIS: "пучок Гиса", PURK: "волокна Пуркинье", VENT: "миокард желудочков",
    SCAR: "рубец (инфаркт)", BORDER: "пограничная зона",
}

# Коэффициенты диффузии, мм^2 / (безразм. ед. времени).
# Скорость проведения в модели CV = 1.36*sqrt(D) мм/ед = 0.105*sqrt(D) м/с:
# миокард ~0.47 м/с, предсердия ~0.7 м/с, АВ-узел ~0.05 м/с,
# пучок Гиса ~1.7 м/с, волокна Пуркинье ~2.8 м/с, пограничная зона инфаркта ~0.2 м/с.
D_TISSUE = {
    NONE: 0.0, ATRIA: 45.0, AVN: 0.5, HIS: 250.0, PURK: 700.0,
    VENT: 20.0, SCAR: 0.0, BORDER: 4.0,
}

PEN_LEN = 6.5  # длина проникающего пучка (зоны перехода АВ-узел -> Гис), мм
# Параметр k по областям (больше k - короче ПД)
K_ENDO, K_APEX, K_EPI, K_PURK = 6.0, 4.0, 7.0, 6.5

ANGLE = np.deg2rad(35.0)  # наклон оси сердца от вертикали влево


def ellipse(X, Y, cx, cy, rx, ry):
    return ((X - cx) / rx) ** 2 + ((Y - cy) / ry) ** 2 <= 1.0


def edist(X, Y, cx, cy, rx, ry):
    """Приближённое расстояние со знаком от точки до эллипса (> 0 снаружи)."""
    # d ~ (q - 1) / |grad q|, q = sqrt(F) - "эллиптический радиус"
    q = np.sqrt(((X - cx) / rx) ** 2 + ((Y - cy) / ry) ** 2)
    g = np.hypot((X - cx) / rx ** 2, (Y - cy) / ry ** 2) / np.maximum(q, 1e-9)
    return (q - 1) / np.maximum(g, 1e-9)


def dilate(m, n):
    """Морфологическое расширение маски на n клеток (4-связность)."""
    m = m.copy()
    for _ in range(n):
        e = m.copy()
        e[1:] |= m[:-1]
        e[:-1] |= m[1:]
        e[:, 1:] |= m[:, :-1]
        e[:, :-1] |= m[:, 1:]
        m = e
    return m


class Heart:
    def __init__(self, dx=0.5, size=(90.0, 95.0), center=(38.0, 38.0),
                 scar=False, av_block=False):
        self.dx = dx
        W, H = size
        nx, ny = int(W / dx), int(H / dx)
        self.shape = (ny, nx)
        self.center = center
        yy, xx = np.mgrid[0:ny, 0:nx] * dx
        self.x, self.y = xx, yy

        # координаты сердца: поворот на ANGLE против часовой (на экране)
        c, s = np.cos(ANGLE), np.sin(ANGLE)
        px, py = xx - center[0], yy - center[1]
        X = c * px - s * py
        Y = s * px + c * py
        self.X, self.Y = X, Y

        t = np.full(self.shape, NONE, dtype=np.int8)

        # --- Предсердия: два эллипса со стенкой ~3 мм и полостями ---
        ra_out = ellipse(X, Y, -12, -16, 14, 13)
        la_out = ellipse(X, Y, 13, -17, 13, 12)
        ra_cav = ellipse(X, Y, -13, -17, 10.5, 9.5)
        la_cav = ellipse(X, Y, 14, -18, 9.5, 8.5)
        atria = (ra_out | la_out) & ~ra_cav & ~la_cav & (Y < -2.0)
        t[atria] = ATRIA

        # --- Желудочки: купол до верхушки, полости ПЖ и ЛЖ ---
        vent_out = ellipse(X, Y, 0, 0, 31, 62) & (Y > 0.5)
        rv_cav = ellipse(X, Y, -15.5, 12, 10, 34) & (Y > -1.0)
        lv_cav = ellipse(X, Y, 10.5, 14, 8.5, 34) & (Y > -1.0)
        vent = vent_out & ~rv_cav & ~lv_cav
        t[vent] = VENT

        # --- Проводящая система желудочков ---
        # Пуркинье - тонкий (~1 мм) слой на эндокарде обеих полостей;
        # ножки пучка идут по перегородке от бифуркации пучка Гиса.
        d_rv = edist(X, Y, -15.5, 12, 10, 34)
        d_lv = edist(X, Y, 10.5, 14, 8.5, 34)
        endo = vent & (((d_rv > 0) & (d_rv <= 1.1)) | ((d_lv > 0) & (d_lv <= 1.1)))
        septum = (X > -6.5) & (X < 3.0)
        purk = endo & ((Y > 12.0) | (septum & (Y > 6.0)))
        # бифуркация пучка Гиса: поперёк перегородки к обеим ножкам
        bif = vent & septum & (np.abs(Y - 7.0) <= 0.7)
        his = (np.abs(X + 1.5) <= 0.8) & (Y > -0.5) & (Y < 7.5)
        t[purk | bif] = PURK
        t[his] = HIS

        # Изоляция проводящей системы соединительнотканной оболочкой:
        # с миокардом она контактирует только в точках - мышечно-
        # пуркиньевских контактах (PMJ) в дистальных отделах, каждые 5 мм.
        cond = np.isin(t, (PURK, HIS))
        sheath = dilate(cond, 2) & (t == VENT)
        pmj = (Y > 12.0) & (np.mod(Y, 5.0) < 0.6)
        t[sheath & ~pmj] = NONE

        # --- АВ-узел: медленный путь от перегородки предсердий к пучку Гиса ---
        avn = (np.abs(X + 1.5) <= 1.3) & (Y >= -10.5) & (Y <= -0.5)
        if av_block:
            avn &= Y > -1.0            # узел перерезан: полная АВ-блокада
            t[(np.abs(X + 1.5) <= 1.3) & (Y >= -10.5) & (Y <= -1.0)] = NONE
        t[avn] = AVN

        # --- Постинфарктный рубец в боковой стенке ЛЖ ---
        # Субэндокардиальный инфаркт: погибают эндокард и волокна Пуркинье,
        # у эпикарда остаётся слой пограничной зоны с замедленным
        # проведением (разобщение клеток, фиброз) и нормальный миокард.
        if scar:
            lat = (X > 3.0) & (Y > 14.0) & (Y < 40.0)
            sc = lat & (d_lv < 5.0) & (Y > 18.0) & (Y < 36.0)
            bz = lat & (d_lv < 6.5) & ~sc
            t[sc & (t != NONE)] = SCAR
            t[bz & (t != NONE)] = BORDER
            self.scar_center = (22.0, 27.0)

        self.type = t
        self.D = np.vectorize(D_TISSUE.get)(t).astype(float)

        # Проникающий пучок: проводимость плавно (геометрически) растёт
        # от АВ-узла к пучку Гиса. Без этого перехода маленький узел не
        # может возбудить "тяжёлую" нагрузку пучка (source-sink mismatch).
        pen = (t == AVN) & (Y > -PEN_LEN - 0.5)
        s = np.clip((Y[pen] + PEN_LEN + 0.5) / PEN_LEN, 0, 1)
        d0, d1 = D_TISSUE[AVN], D_TISSUE[HIS]
        self.D[pen] = d0 * (d1 / d0) ** s
        # Аналогично ножки пучка: от D пучка Гиса у бифуркации до D
        # дистальных волокон Пуркинье на 10 мм ниже.
        pk = t == PURK
        s = np.clip((Y[pk] - 6.0) / 10.0, 0, 1)
        d0, d1 = D_TISSUE[HIS], D_TISSUE[PURK]
        self.D[pk] = d0 * (d1 / d0) ** s

        # синусовый узел - у впадения верхней полой вены (верх ПП)
        self.sa = ellipse(X, Y, -17, -28.0, 3.0, 2.5) & (t == ATRIA)

        # Удаляем островки ткани, не связанные с синусовым узлом
        # (например, кусочки перегородки, отрезанные оболочкой пучка Гиса).
        # Вторая "затравка" - верхушка: при АВ-блокаде желудочки отделены
        # от предсердий, но должны остаться в модели.
        reach = self.sa | (ellipse(X, Y, 0, 55, 3, 3) & (t == VENT))
        while True:
            grown = dilate(reach, 1) & (self.D > 0)
            if grown.sum() == reach.sum():
                break
            reach = grown
        t[(self.D > 0) & ~reach] = NONE
        self.D[~reach] = 0.0

        # Неоднородность длительности ПД (параметр k: больше k - короче ПД).
        # У верхушки ПД короче, чем у основания, на эпикарде короче, чем на
        # эндокарде. Поэтому желудочки реполяризуются в порядке, обратном
        # возбуждению, и зубец T положителен (конкордантен QRS).
        # У волокон Пуркинье ПД самый длинный (иначе они электротонически
        # укорачивают ПД эндокарда и зубец T становится инвертированным).
        vmask = np.isin(t, (VENT, BORDER))
        depth = np.clip(np.minimum(d_rv, d_lv) / 10.0, 0, 1)   # эндо -> эпи
        apex = np.clip(Y / 60.0, 0, 1)                          # основание -> верхушка
        k = np.full(self.shape, 8.0)
        k[vmask] = K_ENDO + K_APEX * apex[vmask] + K_EPI * depth[vmask]
        k[np.isin(t, (HIS, PURK))] = K_PURK
        k[t == ATRIA] = 11.0    # у предсердий ПД короче
        self.k = k

        # "Толщина" стенки поперёк среза для псевдо-ЭКГ (2.5D поправка):
        # стенки предсердий ~2-3 мм, миокард желудочков ~10 мм, а
        # проводящая система - тонкие тяжи с ничтожной долей объёма.
        self.w_ecg = np.ones(self.shape)
        self.w_ecg[t == ATRIA] = 0.25
        self.w_ecg[np.isin(t, (AVN, HIS, PURK))] = 0.001

    def to_screen(self, X, Y):
        """Координаты сердца -> координаты экрана."""
        c, s = np.cos(ANGLE), np.sin(ANGLE)
        return (self.center[0] + c * X + s * Y,
                self.center[1] - s * X + c * Y)

    def electrodes(self, R=150.0):
        """Электроды конечностей по треугольнику Эйнтховена."""
        cx, cy = self.center[0], self.center[1] + 5
        ang = {"RA": -150.0, "LA": -30.0, "LL": 90.0}
        return {n: (cx + R * np.cos(np.deg2rad(a)), cy + R * np.sin(np.deg2rad(a)))
                for n, a in ang.items()}
