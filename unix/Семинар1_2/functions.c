#include <fcntl.h>   /* creat(), open(), O_RDONLY          */
#include <unistd.h>  /* read(), write(), close()            */
#include <string.h>  /* strlen() — только для сообщений     */

#define BUFSIZE 1024

/* Вспомогательная функция: вывод строки-сообщения на экран */
static void print_msg(const char *s)
{
    write(1, s, strlen(s));
}

int main(void)
{
    int  fd;             /* дескриптор файла                */
    char buf[BUFSIZE];   /* буфер для данных                */
    int  len;            /* количество прочитанных байт     */

    const char *filename = "myfile.txt";

    /* ═══════════════════════════════════════════════════════════
       ЧАСТЬ 1 — Создать файл и записать строки с клавиатуры
       ═══════════════════════════════════════════════════════════ */

    /*
     * creat(pathname, mode)
     *   pathname — имя создаваемого файла
     *   mode     — права доступа (0644 = rw-r--r--)
     *   return   — дескриптор файла (>= 0) или -1 при ошибке
     *
     * Эквивалентно: open(filename, O_WRONLY | O_CREAT | O_TRUNC, 0644)
     * Файл открывается ТОЛЬКО для записи.
     */
    fd = creat(filename, 0644);
    if (fd < 0) {
        write(2, "Ошибка: creat() не выполнен\n", 29);
        return 1;
    }

    print_msg("Введите строки (пустая строка — завершение):\n");

    /* ─── Цикл ввода строк с клавиатуры и записи в файл ─── */
    while (1) {

        /*
         * read(fd, buf, count)
         *   fd    = 0  — стандартный ввод (клавиатура)
         *   buf        — буфер, куда записываются данные
         *   count      — максимальное число байт для чтения
         *   return     — реально прочитанных байт, 0 = EOF, -1 = ошибка
         *
         * В каноническом (терминальном) режиме read возвращает управление
         * после нажатия Enter. Строка ВКЛЮЧАЕТ символ '\n'.
         */
        len = read(0, buf, sizeof(buf));

        if (len <= 0) break;                    /* EOF (Ctrl+D) или ошибка */

        /* Пустая строка: пользователь нажал Enter сразу.
           В этом случае len == 1, buf[0] == '\n' */
        if (len == 1 && buf[0] == '\n')
            break;

        /*
         * write(fd, buf, count)
         *   fd   — дескриптор файла (получен от creat)
         *   buf  — буфер с данными
         *   len  — сколько байт записать
         * Записываем ровно то, что прочитали (включая '\n')
         */
        write(fd, buf, len);
    }

    /*
     * close(fd) — закрывает файл:
     *   сбрасывает буферы ядра на диск,
     *   освобождает дескриптор для повторного использования.
     */
    close(fd);

    /* ═══════════════════════════════════════════════════════════
       ЧАСТЬ 2 — Открыть файл на чтение и вывести содержимое
       ═══════════════════════════════════════════════════════════ */

    /*
     * open(pathname, flags)
     *   O_RDONLY — только для чтения
     *   return   — дескриптор файла (>= 0) или -1 при ошибке
     */
    fd = open(filename, O_RDONLY);
    if (fd < 0) {
        write(2, "Ошибка: open() не выполнен\n", 28);
        return 1;
    }

    print_msg("\n─── Содержимое файла ───\n");

    /* ─── Цикл чтения из файла и вывода на экран ─── */
    while ((len = read(fd, buf, sizeof(buf))) > 0) {
        /*
         * write(fd, buf, count)
         *   fd = 1 — стандартный вывод (экран)
         * Строки завершены '\n', а не '\0' — как требует задание.
         */
        write(1, buf, len);
    }

    close(fd);   /* закрыть файл после чтения */

    return 0;
}