#ifndef COMMON_H
#define COMMON_H

#include <stdatomic.h>
#include <sys/ipc.h>

/* Ключ сегмента обе программы получают одинаково: ftok от одного и того же
 * файла и одного и того же номера проекта. В исходном примере вторым
 * аргументом был getpid(), из-за чего у каждого процесса получался свой
 * ключ и свой сегмент, так что обмена между программами бы не было. */
#define KEY_FILE "common.h"
#define KEY_PROJ 'P'

// Состояние обмена: кто сейчас должен работать с сегментом.
enum state {
	ST_EMPTY = 0, // запроса нет (так выглядит только что созданный сегмент)
	ST_REQUEST,   // первая программа записала число, ждёт ответа
	ST_DONE,      // вторая программа записала результат
	ST_QUIT       // первая программа закончила работу
};

// Результат проверки числа.
enum verdict {
	V_NONE = 0,  // 0 и 1 не простые и не составные
	V_PRIME,
	V_COMPOSITE
};

// Что лежит в разделяемой памяти.
struct shared {
	/* Поле state меняется атомарно: запись result/verdict гарантированно
	 * становится видна другому процессу раньше, чем новое состояние. */
	atomic_int state;
	unsigned long long value; // проверяемое число
	int verdict;              // enum verdict
};

// Пауза между проверками памяти, мкс.
#define POLL_USEC 10000

#endif
