#include <stdlib.h>
#include <dirent.h>
#include <errno.h>
#include "dir.h"

readdir_res *
readdir_1_svc(nametype *argp, struct svc_req *rqstp)
{
	static readdir_res result;

	DIR *dirp;
	struct dirent *d;
	namelist nl;
	namelist *nlp;

	(void)rqstp;

	dirp = opendir(*argp);
	if( dirp == (DIR *) NULL)
	{
		/* Каталог не открылся: клиент получит errno и пустое объединение. */
		result.err = errno;
		return &result;
	}

	/* Снять предыдущий успешный результат, иначе список течёт при каждом вызове. */
	xdr_free((xdrproc_t) xdr_readdir_res, (char *) &result);

	/* nlp — адрес поля, в которое записывается очередной узел. */
	nlp = &result.readdir_res_u.list;
	while( d = readdir(dirp))
	{
		nl = *nlp = (namenode *) malloc(sizeof(namenode));
		if( nl == (namenode *) NULL )
		{
			result.err = EAGAIN;
			closedir(dirp);
			return &result;
		}
		nl->name = strdup(d->d_name);
		nlp = &nl->next;
	}
	*nlp = (namelist)NULL;
	result.err = 0;
	closedir(dirp);

	return &result;
}
