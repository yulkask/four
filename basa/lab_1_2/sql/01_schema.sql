SET NAMES utf8mb4;

CREATE DATABASE IF NOT EXISTS library
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE library;

DROP TABLE IF EXISTS books;

CREATE TABLE books (
    id         INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    authors    VARCHAR(255)  NOT NULL COMMENT 'Авторы',
    title      VARCHAR(255)  NOT NULL COMMENT 'Название',
    publisher  VARCHAR(150)  NOT NULL COMMENT 'Издательство',
    pub_year   VARCHAR(4)    NOT NULL COMMENT 'Год издания',
    annotation TEXT          NOT NULL COMMENT 'Аннотация',
    PRIMARY KEY (id),
    -- год хранится как текст, но должен состоять ровно из 4 цифр
    CONSTRAINT chk_year CHECK (pub_year REGEXP '^[0-9]{4}$')
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci
  COMMENT = 'Описание книг';

